/*
 * 康熙笔画异说表（可选流派差异）
 * 部分汉字在不同姓名学流派/版本中存在两种（甚至多种）康熙笔画说法，例如「陳」有 15/16 两说。
 * 主值取自 kangxi-strokes.js（权威康熙笔画，默认采用主流说法），此处仅记录「另有 N 画一说」的备选值，
 * 供用户在姓名学中查看提示并按异说笔画切换重算。不改变默认主值，确保五格剖象结果稳定可复现。
 * 纯本地、零依赖、零外链。
 */
(function (root) {
  'use strict';

  // char -> 异说笔画数组（支持多种流派）；仅作提示与可切换重算，不影响主值
  var ALT = {
    '陳': [15],            // 另说 15 画（主流取 16）
    '陈': [15],            // 简体对应异说
    '沾': [9],             // 另说 9（主流取 10）
    '淫': [11],            // 另说 11（主流取 12）
    '蕊': [15, 18],        // 三说：15/18（主流取 18）
    '达': [12, 16],        // 另说 12/16（主流取 16）
    '礼': [17, 18],        // 另说 17/18（主流取 18）
    '净': [11],            // 另说 11（主流取 12）
    '准': [10, 14]         // 另说 10/14（主流取 14）
  };

  root.KANGXI_ALT_STROKES = ALT;
  if (typeof module !== 'undefined' && module.exports) module.exports = ALT;
})(typeof globalThis !== 'undefined' ? globalThis : (typeof window !== 'undefined' ? window : this));
